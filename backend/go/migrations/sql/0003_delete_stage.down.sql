-- Откат 0003: lake снова знает только пять стадий конвейера §4.
--
-- ОТКАТ НЕ ВСЕГДА ВЫПОЛНИМ. Проверка принадлежности срабатывает и на уже
-- записанных строках, поэтому при наличии событий стадии delete откат упадёт с
-- нарушением ck_raw_events_stage — и это правильное поведение: ограничение
-- защищает данные, а не сообщает об ошибке. Откатывать надо на базе, где
-- удалений ещё не было (или после их вычистки вручную, что для lake плохая
-- идея — журнал только на добавление).
--
-- Данные при этом не теряются молча: если строки стадии delete есть, откат
-- падает ДО того, как ограничение изменится, то есть старая редакция
-- ограничения остаётся в силе.

ALTER TABLE raw_events DROP CONSTRAINT ck_raw_events_stage;

ALTER TABLE raw_events ADD CONSTRAINT ck_raw_events_stage CHECK (stage IN ('collect','normalize','enrich','index','derive'));

COMMENT ON CONSTRAINT ck_raw_events_stage ON raw_events IS
    'Допустимые стадии lake: пять стадий конвейера §4 (миграция 0003 добавляла '
    'шестую — delete — и была откачена). Набор зафиксирован в domain.AllStages.';
