-- Надгробие удаления в lake (§4, стадия index: «удаление — через
-- событие-надгробие (tombstone)»; §9, «документ, удалённый в источнике,
-- исчезает из выдачи»).
--
-- ОТДЕЛЬНАЯ МИГРАЦИЯ, А НЕ ПРАВКА 0002. 0002 применена, и переписывать
-- применённую миграцию нельзя: у разработчика, у которого версия схемы уже
-- 2, файл изменился бы без версии, и migrate не заметил бы расхождения. CHECK
-- меняется новой версией схемы — ровно так же, как это сделано для любой другой
-- эволюции lake.
--
-- ЧТО МЕНЯЕТСЯ. В ck_raw_events_stage появляется шестая стадия — delete.
-- До этого ограничения lake умело записать ровно пять стадий конвейера §4, и
-- удаление не помещалось ни в одну: документ, удалённый в источнике, не мог
-- оставить в lake ни единого следа, а значит пересборка индекса (§1, принцип 1
-- — «любой индекс можно удалить и воссоздать из lake») была невозможна в
-- принципе: новое состояние документа неотличимо от старого.
--
-- ПОЧЕМУ ЭТО СТАДИЯ, А НЕ ФЛАГ В ТЕЛЕ СОБЫТИЯ. Разбор в
-- internal/envelope/event.go (Stage.DeleteStage): флаг tombstone внутри события
-- стадии index заставил бы править каждого потребителя (§1, принцип 6) и не
-- дал бы надгробию собственного ключа идемпотентности.
--
-- ОГРАНИЧЕНИЕ ПЕРЕПИСЫВАЕТСЯ ЦЕЛИКОМ, А НЕ ДОБАВЛЯЕТСЯ. CHECK в Postgres не
-- расширяют: «stage IN (пять) OR stage = 'delete'» выглядело бы мягче, но
-- через год кто-то добавит седьмую стадию таким же «мягким» способом, и
-- ограничение станет списком, который никто не читает. Перечисление остаётся
-- перечислением — ровно таким же, каким его читает домен (domain.AllStages).
--
-- ПОРЯДОК В ПЕРЕЧИСЛЕНИИ ЗНАЧИМ ДЛЯ ЧТЕНИЯ, НО НЕ ДЛЯ ПРОВЕРКИ. CHECK
-- проверяет принадлежность, а не позицию; порядок повторяет конвейер §4, чтобы
-- строку можно было читать глазами и сравнивать с domain.AllStages().

ALTER TABLE raw_events DROP CONSTRAINT ck_raw_events_stage;

ALTER TABLE raw_events ADD CONSTRAINT ck_raw_events_stage CHECK (stage IN ('collect','normalize','enrich','index','derive','delete'));

COMMENT ON CONSTRAINT ck_raw_events_stage ON raw_events IS
    'Допустимые стадии lake: пять стадий конвейера §4 плюс надгробие удаления (delete). '
    'Набор зафиксирован и в domain.AllStages — событие стадии вне этого списка '
    'невалидно ещё до записи, а это значит, что и в ограничении его быть не должно.';

