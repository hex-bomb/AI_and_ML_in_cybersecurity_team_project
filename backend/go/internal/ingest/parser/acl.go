// Права в карте metadata конверта.
//
// §4 перечисляет их среди полей конверта (`acl` — список принципалов), §6
// называет контейнер `space_id` и требует, чтобы ACL ехал вместе с документом
// на каждом шаге, включая индекс. Метаданные конверта — единственное место,
// где права лежат до стадии index: ParsedDocument несёт их в своей карте, и
// разбирать их где-то ещё означало бы завести второе место правды.
//
// Имена полей не выносятся наружу: читатель здесь один — RightsFromMetadata, —
// а тесты пишут строкой. Константа, на которую ссылается и код, и тест,
// проверила бы саму себя и молчала бы при переименовании, которое сломало бы
// конверты, написанные раньше.
const (
	metadataSpaceID = "space_id"
	metadataACL     = "acl"
)

// RightsFromMetadata собирает domain.DocumentRights из полей прав конверта.
//
// Это единственный разбор прав на стороне конвейера: стадия index получает
// права одним значением и проставляет их каждому чанку документа. Чанк без
// прав не виден никому — terms по ненаписанному полю не совпадает ни с чем, —
// то есть отказ закрытый, и цена ошибки здесь обратная ожидаемой: не утечка, а
// документ в статусе ready, которого не находит поиск.
//
// Что здесь НЕ делается и почему:
//
//   - Права не разрешаются. Список тех, кому документ виден, зависит от прав,
//     меняющихся без переиндексации (§6), и считается на стороне запроса из
//     AccessScope. Считать его здесь значило бы запечь в индекс снимок прав.
//
//   - Права не расширяются и не подменяются. Единственное решение, принимаемое
//     по форме, — «контейнер плюс точечные исключения».
//
//   - Отсутствие полей — не ошибка. Документ, которому права не объявили,
//     получает пустые DocumentRights и не виден НИКОМУ. Падать на этом нельзя:
//     заметка без объявленного контейнера — законное состояние (§6: права
//     личных заметок — `acl = [user:<id>] и больше никто`), и загрузка
//     документа без прав должна доезжать до индексации, а не падать на входе.
//
// ГРАНИЦА ДОВЕРИЯ, которую этот файл НЕ закрывает. Поле space_id приезжает в
// конверте от коннектора (§4), а у коннектора нет хода к таблице прав: он
// публикует документ в контейнер, название которого прислал источник. Ни здесь,
// ни в сценарии загрузки объявленный container_key не сверяется с acl_containers и с
// цепочкой AGDLP, поэтому объявить можно ЛЮБОЙ контейнер своего тенанта, включая
// чужой.
//
// Последствие: документ, опубликованный в чужой контейнер, наследует права этого
// контейнера и становится виден всем, кому контейнер открыт. Это отдельная от
// переопределения ACL дыра, и она НЕ лечится разбором прав.
//
// Что для этого нужно (вне этой правки): сохранять актора загрузки — колонка
// document_versions.author в миграции 0002 уже есть, но её никто не заполняет,
// DocumentCreateParams актора не несёт, — и проверять объявленный контейнер оракулом
// прав того же актора (ACLResolver.RequireReadSpace проверку уже умеет, ему не
// хватает субъекта). Пока актора нет, индекс может унаследовать только
// объявленный контейнер, и это остаётся открытым.
//
// Неверная ФОРМА объявленных прав — ошибка, а не тихий отказ. Молча выброшенный
// контейнер превратил бы документ в личную заметку без владельца, то есть в
// невидимый никому документ, и оператор увидел бы «успешно обработанный
// документ, который не ищется». Потерянный список исключений опаснее: документ
// стал бы виден всем, у кого есть права на контейнер, — это утечка. Ошибка
// отправляет версию в failed с кодом, по которому причину видно, — ровно то,
// чего требует обработка битого файла выше по потоку.
func RightsFromMetadata(meta map[string]any) (domain.DocumentRights, error) {
	space, err := containerFrom(meta)
	if err != nil {
		return domain.DocumentRights{}, err
	}
	terms, err := exceptionTermsFrom(meta)
	if err != nil {
		return domain.DocumentRights{}, err
	}
	// DocumentRightsFor приводит термы к канону сам: обрезает внешние пробелы,
	// убирает пустые, сортирует и склеивает дубли. Повторная нормализация в
	// конверте не нужна — словарь принципалов остаётся в одном месте.
	return domain.DocumentRightsFor(space, terms), nil
}

// containerFrom читает контейнер документа — §6, «права висят на контейнере».
//
// nil и отсутствие ключа означают одно и то же: контейнер не объявлен. Это
// законное состояние личной заметки и неисправного импорта, и различать их
// нечем: в обоих случаях документ не получает права на контейнер.
func containerFrom(meta map[string]any) (string, error) {
	raw, ok := meta[metadataSpaceID]
	if !ok || raw == nil {
		return "", nil
	}
	space, ok := raw.(string)
	if !ok {
		return "", invalidRights(metadataSpaceID, raw)
	}
	// Пробелы обрежет DocumentRightsFor: обрезка внешних пробелов — единственная
	// нормализация, безопасная здесь, потому что форму принципала задаёт
	// конверт, а не этот пакет.
	return space, nil
}

// exceptionTermsFrom читает точечные исключения документа.
//
// Принимаются обе формы, потому что карта приходит из двух мест: []string —
// когда метаданные собраны кодом (повторная сборка, тесты), и []any с той же
// формой после похода через JSON — когда их прислал клиент или они прочитаны
// из jsonb. Различать эти случаи здесь нечем: список строк в обоих один.
//
// Список, который списком не является (строка, число, объект), отвергается:
// иначе `acl = "user:anna"` молча стал бы одним исключением там, где автор
// ждал список, а `acl = {}` — пустым, то есть «исключений нет».
func exceptionTermsFrom(meta map[string]any) ([]string, error) {
	raw, ok := meta[metadataACL]
	if !ok || raw == nil {
		return nil, nil
	}
	switch list := raw.(type) {
	case []string:
		return list, nil
	case []any:
		terms := make([]string, 0, len(list))
		for _, item := range list {
			term, ok := item.(string)
			if !ok {
				return nil, invalidRights(metadataACL, item)
			}
			terms = append(terms, term)
		}
		return terms, nil
	default:
		return nil, invalidRights(metadataACL, raw)
	}
}

// invalidRights — единый отказ на неверную форму поля прав.
//
// В детали уходит ТОЛЬКО имя поля и тип значения: само значение пришло от
// клиента, детали ошибки уходят в HTTP как есть, и эхо чужой строки в ответе —
// лишний канал утечки того, чего оператору знать не нужно.
func invalidRights(field string, value any) error {
	return domain.InvalidMetadata("Поле прав " + field + " конверта имеет неверную форму").
		WithDetails(map[string]any{"field": field, "got": fmt.Sprintf("%T", value)})
}

// normalizeRightsMetadata приводит объявленные права к канонической форме.
//
// Нормализация нужна не красоте, а двум вещам. Первая: parsed.json уходит на
// диск и оттуда читается повторно (пересборка индекса из lake, §1), поэтому
// два одинаковых по смыслу объявления обязаны давать один и тот же файл —
// иначе повторная индексация того же документа даст другой diff. Вторая:
// разбор читает права обратно тем же RightsFromMetadata, и канон, записанный
// один, не может разъехаться с тем, чего ждёт читатель.
//
// Ключи, которых не было, не добавляются: пустой acl в конверте означал бы
// «исключений нет» и на деле сделал бы документ с контейнером видимым всем, у
// кого есть права на этот контейнер. Отсутствие ключа и пустой список —
// разные вещи, и первое остаётся первым.
func normalizeRightsMetadata(meta map[string]any) error {
	rights, err := RightsFromMetadata(meta)
	if err != nil {
		return err
	}
	if _, ok := meta[metadataSpaceID]; ok {
		meta[metadataSpaceID] = rights.SpaceID
	}
	if _, ok := meta[metadataACL]; ok {
		meta[metadataACL] = rights.ExceptionTerms()
	}
	return nil
}
