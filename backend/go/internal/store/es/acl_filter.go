package elasticsearch

import (
	"slices"
	"strings"

	domain "github.com/kbsearch/kb/internal/envelope"
)

// Файл строит фильтр прав §6 — это единственное место адаптера, где решается,
// какие документы пользователь вообще может увидеть.
//
// Почему фильтр в запросе, а не список (дорожная карта §6 и ошибка №2 из §2):
// post-filter приносит запрещённый чанк в память процесса, в контекст LLM и в
// логи ДО того, как сработала проверка. Поэтому domain.AccessScope описывает
// права термами индекса (space_id + acl), и подставляются они в тело запроса.
// Список разрешённых document_id сюда не попадает и попасть не может: такого
// поля в AccessScope нет, и это проверяется тестом в scoped_query_test.go.
//
// Почему именно такая форма (слова §6): права висят на контейнере space_id,
// а acl документа нужен только для точечных исключений («права личных заметок:
// acl = [user:<id>]»). Смена прав на space применяется мгновенно и НЕ требует
// переиндексации документов: пересчитывается лишь список доступных space у
// пользователя (кэш на минуту-две, сбрасывается событием acl.changed). Если бы
// права лежали внутри документа, отзыв доступа ждал бы переиндексации всех его
// чанков — это и есть главный риск, названный вендорным разбором (§6).
//
// Почему НЕ document-level security Elasticsearch (решение §6): наши
// пользователи — не пользователи ES, а по документации ограничений DLS
// terms-lookup в ролевых запросах не поддерживается, статистика релевантности
// считается без учёта фильтра роли, а агрегации могут раскрывать термины из
// недоступных документов. Фильтр строит наш Go-код, и агрегации по чужим
// данным отдаются только после того же фильтра. Не «упрощайте» это переездом
// на DLS.

const (
	// aclFieldSpace — контейнер документа (§6): канал Slack, папка, ящик.
	// Права висят на нём, поэтому смена прав на space не трогает индекс.
	aclFieldSpace = "space_id"
	// aclFieldPrincipals — точечные исключения на самом документе (§6).
	aclFieldPrincipals = "acl"
)

// aclAccessClause превращает область доступа в РОВНО ОДНУ клозу фильтра §6:
//
//	{"bool": {"should": [{"terms": {"space_id": [...]}},
//	                       {"terms": {"acl": [...]}}],
//	          "minimum_should_match": 1}}
//
// Одна клоза, а не список, — чтобы вызывающая сторона не могла её «забыть»:
// отсутствие фильтра читается как «доступны все документы тенанта».
//
// minimum_should_match обязателен: без него should внутри bool без must
// при отсутствии совпадений даёт пустую выборку по умолчанию в некоторых
// версиях, а нам нужен явный контракт «хотя бы одна ветка совпала».
//
// Пустая область — это «нечего не видно», а не «фильтр не задан»: вернуться
// должен denyAllClause.
func aclAccessClause(scope domain.AccessScope) any {
	spaces := aclTerms(scope.SpaceIDs)
	principals := aclTerms(scope.Principals)
	if len(spaces) == 0 && len(principals) == 0 {
		return denyAllClause()
	}
	should := make([]any, 0, 2)
	// Пустую ветку не добавляем: terms с пустым массивом не матчит ничего и
	// только раздувает тело запроса. Совпадения всё равно не будет — запрос
	// закрыт по другой ветке.
	if len(spaces) > 0 {
		should = append(should, map[string]any{"terms": map[string]any{aclFieldSpace: spaces}})
	}
	if len(principals) > 0 {
		should = append(should, map[string]any{"terms": map[string]any{aclFieldPrincipals: principals}})
	}
	return map[string]any{"bool": map[string]any{
		"should":               should,
		"minimum_should_match": 1,
	}}
}

// denyAllClause — match_none: запрос, который не может совпасть ни с одним
// документом. Это единственный честный ответ на пустую область доступа.
//
// Почему не пустой terms и не отсутствие фильтра: и то и другое в Elasticsearch
// означает «не ограничивать» — это полный обход прав, а не пустая выдача
// (то же замечание, что у filterClauses для document_id). match_none стоит
// внутри filter рядом с term по тенанту, поэтому fail-closed получается
// структурно: забыть его нельзя, он всегда часть запроса.
func denyAllClause() any {
	return map[string]any{"match_none": map[string]any{}}
}

// aclTerms готовит список термов фильтра: без пустых строк, без дублей, в
// стабильном порядке.
//
// nil обязан превратиться в пустой, но НЕ nil срез: null в terms означает
// «не ограничивать» — ровно та ошибка, которую уже пришлось закрывать для
// document_id. Срез здесь всегда новый, чужие данные не мутируются.
//
// Форма принципала не меняется: только внешние пробелы. Строку задаёт конверт
// (domain.AccessScopeFor): «user:<id>», «role:<имя>», «group:<имя>», а со
// стороны источников — ресурсные группы «res:space-platform:read» (§6).
func aclTerms(raw []string) []string {
	out := make([]string, 0, len(raw))
	for _, value := range raw {
		if trimmed := strings.TrimSpace(value); trimmed != "" {
			out = append(out, trimmed)
		}
	}
	// Порядок термов на запрос не влияет, но повторяемость нужна тестам,
	// логам и diff'ам тел запросов — те же соображения, что в AccessScopeFor.
	slices.Sort(out)
	return slices.Compact(out)
}

